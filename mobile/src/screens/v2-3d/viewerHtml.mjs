  '    if (markerVao) { gl.deleteBuffer(markerBuffer); gl.deleteVertexArray(markerVao); }',
  '    if (program) gl.deleteProgram(program);',
  '    if (markerProgram) gl.deleteProgram(markerProgram);',
  '    var lose = gl.getExtension("WEBGL_lose_context");',
